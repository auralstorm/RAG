export function exampleAnswer(question: string) {
  const example = Object.hasOwn(examples, question)
    ? examples[question]
    : undefined;
  return example
    ? `**示例回答**\n\n${example}`
    : '当前示例没有覆盖这个问题。你可以选择一个推荐问题，体验问答流程。';
}
