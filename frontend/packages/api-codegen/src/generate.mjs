// Generate types from committed OpenAPI/JSON Schema; never fetch an external specification.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { format } from 'prettier';

const root = new URL('../../../../', import.meta.url);
const check = process.argv.includes('--check');
const header = '// Generated by make contracts. Edit backend DTOs instead.\n';

async function readJson(path) {
  return JSON.parse(await readFile(new URL(path, root), 'utf8'));
}

function convertReferences(value) {
  if (Array.isArray(value)) return value.map(convertReferences);
  if (value !== null && typeof value === 'object') {
    const converted = Object.fromEntries(
      Object.entries(value).map(([key, child]) => [
        key,
        key === '$ref' &&
        typeof child === 'string' &&
        child.startsWith('#/$defs/')
          ? child.replace('#/$defs/', '#/components/schemas/')
          : convertReferences(child),
      ]),
    );
    // OpenAPI discriminator mappings contain reference strings without a $ref key.
    const mapping = value.discriminator?.mapping;
    if (mapping && typeof mapping === 'object') {
      converted.discriminator.mapping = Object.fromEntries(
        Object.entries(mapping).map(([tag, reference]) => [
          tag,
          typeof reference === 'string' && reference.startsWith('#/$defs/')
            ? reference.replace('#/$defs/', '#/components/schemas/')
            : reference,
        ]),
      );
    }
    return converted;
  }
  return value;
}

const catalog = await readJson('docs/api/schema-catalog.json');
if (catalog.schema_version !== '1.0' || !Array.isArray(catalog.schemas)) {
  throw new Error('Unsupported schema catalog version');
}
const groups = new Map();
for (const entry of catalog.schemas) {
  if (entry.frontend_group === null) continue;
  if (
    entry.visibility !== 'public' ||
    !['common', 'iam', 'knowledge', 'retrieval'].includes(
      entry.frontend_group,
    ) ||
    !/^schemas\/[a-z0-9/-]+\.json$/.test(entry.path) ||
    !/^[A-Za-z][A-Za-z0-9]+$/.test(entry.name)
  ) {
    throw new Error('Invalid public schema registration');
  }
  const schemas = groups.get(entry.frontend_group) ?? Object.create(null);
  groups.set(entry.frontend_group, schemas);
  const { $defs = {}, ...schema } = await readJson(`docs/api/${entry.path}`);
  // Standalone files declare their dialect; embedded definitions inherit OpenAPI 3.1's dialect.
  delete schema.$schema;
  for (const [definition, value] of Object.entries({
    ...$defs,
    [entry.name]: schema,
  })) {
    const converted = convertReferences(value);
    if (
      definition in schemas &&
      JSON.stringify(schemas[definition]) !== JSON.stringify(converted)
    ) {
      throw new Error(`Conflicting public schema: ${definition}`);
    }
    schemas[definition] = converted;
  }
}

// This in-memory document only adapts reusable JSON Schema to the generator.
// API operations always come from the application's actual OpenAPI document.
const sources = [['openapi.ts', await readJson('docs/api/openapi.json')]];
for (const [group, schemas] of groups) {
  sources.push([
    `${group}.ts`,
    {
      openapi: '3.1.0',
      info: {
        title: `Reusable ${group} schemas`,
        version: catalog.schema_version,
      },
      paths: {},
      components: { schemas },
    },
  ]);
}

const formatOptions = await readJson('.prettierrc.json');
for (const [filename, source] of sources) {
  const types = await format(
    header +
      astToString(
        await openapiTS(source, {
          immutable: true,
          defaultNonNullable: filename !== 'common.ts',
        }),
      ),
    { ...formatOptions, parser: 'typescript' },
  );
  const target = new URL(
    `frontend/packages/api-client/src/generated/${filename}`,
    root,
  );
  if (check) {
    const existing = await readFile(target, 'utf8').catch((error) => {
      if (error.code === 'ENOENT') return undefined;
      throw error;
    });
    if (existing !== types) {
      throw new Error(
        `Generated API types are stale: ${filename}; run make contracts`,
      );
    }
  } else {
    await mkdir(dirname(fileURLToPath(target)), { recursive: true });
    await writeFile(target, types);
  }
}
